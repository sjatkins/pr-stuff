"""Generate src/names.py: the game's fixed vocabularies as enums.

Source is py_json/src/prworld/names.json (itself extracted from the C name
tables by py_json/tools/gen_names.py). Run from py-pr:

    uv run python tools/gen_enums.py

Code tables (sex, position, item kind ...) become ``CodedStrEnum`` classes:
the value is the string exactly as the game spells it, which is what the
JSONL carries, and each member also carries the numeric code (table index).

Bit tables (room flags, affect bits, immunities ...) become ``CodedFlag``
classes, ``enum.Flag`` subclasses: one member per bit, so a field holding a
set of them is one integer and membership, any-of and all-of tests are single
AND operations. Each member carries the game's ``label`` string and its bit
``code``; the list of labels the JSONL carries is converted at the model
boundary (``from_names`` / ``names``), which pydantic does automatically.
"""
