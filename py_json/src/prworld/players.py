def read_pulse_affect(r: Reader) -> dict[str, Any]:
    fields: dict[int, tuple[str, Callable[[], Any]]] = {}
    for tag, name in PULSE_FIELDS.items():
        if name in PULSE_STRINGS:
            fields[tag] = (name, r.sd)
        elif name == "bitvector":
            fields[tag] = (name, lambda: ext_bits(list(struct.unpack("<8I", r.raw(32))), TABLES["affected_bits"]))
        else:
            fields[tag] = (name, (lambda k: lambda: r.field(k))(f"pa.{name}"))
    rec = read_sub(r, PULSE_AFFECT_END, fields, "pulse affect")
    if "type" in rec:
        rec["type_name"] = attack_name(rec["type"])
    if "damage_type" in rec:
        rec["damage_type"] = attack_type(rec["damage_type"])
    for k in ("proc_type", "initial_type", "finish_type"):
        if k in rec:
            rec[k] = name_at(TABLES["pulse_types"], rec[k])
    for k in ("location", "location_initial", "location_finish"):
        if k in rec:
            rec[k] = name_at(TABLES["apply_types"], rec[k])
    return rec


