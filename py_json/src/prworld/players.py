def read_player(data: bytes, source: str, opt: Options) -> dict[str, Any]:
    r = Reader(data, source)
    p = new_player(source)
    f = r.field

    def setf(name: str, key: str):
        return lambda: p.__setitem__(name, f(key))

    def sets(name: str):
        return lambda: p.__setitem__(name, r.sd())

    def settime(name: str):
        return lambda: p["time"].__setitem__(name, r.time32())

    def skills_list(target: str, table: list[str]):
        def fn():
            n = r.counted(4)
            for _ in range(n):
                num, learned = r.num("u16"), r.num("s16")
                p[target].append(skill_entry(num, learned, table))
        return fn

    def remorts():
        n = r.counted(LAYOUT["sizeof.remort_data"]["size"])
        for _ in range(n):
            flag, count, mod, bonus = struct.unpack("<iiii", r.raw(16))
            p["remort_bonuses"].append({"remort_flag": flag, "remort_count": count,
                                        "stat_modifier": mod, "stat_bonus": bonus})

    def kills():
        n = r.counted(LAYOUT["sizeof.kill_info"]["size"])
        for _ in range(n):
            vnum, nk = struct.unpack("<IH2x", r.raw(8))
            if vnum or nk:
                p["kills"].append({"vnum": vnum, "count": nk})

    def affected_array():
        size = LAYOUT["sizeof.affected_type"]["size"]
        n = r.counted(size)
        for _ in range(n):
            chunk = r.raw(size)
            typ, dur, mod, loc = struct.unpack_from("<IiiB", chunk, 0)
            words = list(struct.unpack_from("<8I", chunk, 16))
            p["affects"].append({"type": typ, "type_name": attack_name(typ), "duration": dur, "modifier": mod,
                                 "location": name_at(TABLES["apply_types"], loc),
                                 "bitvector": ext_bits(words, TABLES["affected_bits"])})

    def old_cmd_list(target: str):
        def fn():
            vals = r.array("s32")   # server discards these (numeric ids from an older build)
            if vals:
                p.setdefault("legacy_" + target, vals)
        return fn

    def objlist_after_marker(target: str):
        def fn():
            r.u16()   # SUB_OBJECT
            p[target] = read_obj_list(r, opt)
        return fn

    def wear():
        pos = r.u16()
        r.u16()   # SUB_OBJECT
        items = read_obj_list(r, opt)
