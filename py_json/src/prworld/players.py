def finish_char(p: dict[str, Any], opt: Options) -> None:
    """The version upgrades in player.save.c finish_char, so every record has
    current (version 6) semantics."""
    v = p["file_version"]
    if v > CURRENT_PLAYER_FILE_VERSION:
        opt.warn(f"{p['source']}: unknown player file version {v}")
        return
    if v <= 0:
        if p["weight"] is not None:
            p["weight"] = p["weight"] * 100          # POUNDS_TO_DECIM
        if p["height"] is not None:
            p["height"] = (p["height"] * 10) // 13   # CM_TO_GOBITS
    if v <= 2:
        wimpy = name_at(TABLES["player_bits"], 4)
        if wimpy in p["act"]:
            p["whimpy_level"] = (p["hit"] or 0) // 5
            p["act"].remove(wimpy)
    if v <= 5:
        # clan 1 ("Protected") min_join_level is 20 in clans.current
        if (p["level"] or 0) > 20:
            p["clan"] = 1
        corrupt = name_at(TABLES["player_bits"], 24)
        if corrupt in p["act"]:
            p["act"].remove(corrupt)
            p["clan"] = 2
    if p["name"]:
        p["name"] = p["name"][0].upper() + p["name"][1:].lower()
    if not p["namelist"] and p["name"]:
        p["namelist"] = p["name"].lower()


