"""Readers for the binary player (``stash/<a-z>/<name>``) and account
(``account/<a-z>/<name>``) save files.

These are the hand-coded tagged-record formats written by ``src/player.save.c``
(``load_char_with_path``), ``src/account.c`` (``load_acct``) and
``src/objdb.c`` (``ReadObject`` / ``ReadObjList`` for carried items). Each
record is a stream of ``u16 id`` followed by a payload whose size is the C
field's size; ``player_layout.json`` (generated by ``tools/layout.c`` against
the server headers) supplies those sizes and signedness so the Python reader
matches the compiled server exactly.

Files can be read straight out of a ``.tar`` backup or from an extracted
directory tree.
"""

