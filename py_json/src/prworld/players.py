FMT = {"u8": "<B", "s8": "<b", "u16": "<H", "s16": "<h", "u32": "<I", "s32": "<i",
       "u64": "<Q", "s64": "<q", "f64": "<d", "f32": "<f"}


class FormatError(Exception):
    pass


def _bit_name(table: list[str], n: int) -> str:
    return table[n] if n < len(table) and table[n] else f"bit{n}"


def bits(value: int, table: list[str]) -> list[str]:
    """Names of the set bits in a 32-bit flag word."""
    return [_bit_name(table, i) for i in range(32) if value & (1 << i)]


def ext_bits(words: list[int], table: list[str]) -> list[str]:
    """Names of the set bits in a u32[8] extended bitvector."""
    return [_bit_name(table, w * 32 + i) for w, word in enumerate(words) for i in range(32) if word & (1 << i)]


def name_at(table: list[str], idx: int | None) -> str | None:
    """Table entry for ``idx``; ``"#<idx>"`` when out of range so the field is
    always a string."""
    if idx is None:
        return None
    return table[idx] if 0 <= idx < len(table) and table[idx] else f"#{idx}"


PROF_BASE, SKILL_BASE = 5000, 10000


def skill_entry(num: int, learned: int, table: list[str]) -> dict[str, Any]:
    """Skill numbers: <5000 skills, 5000+ weapon proficiencies (PROF_BASE),
    10000+ skills again (SKILL_BASE); see skills.c boot_class / find_skill_entry."""
    if num >= SKILL_BASE:
        return {"number": num, "kind": "skill", "name": name_at(TABLES["skills"], num - SKILL_BASE), "learned": learned}
    if num >= PROF_BASE:
        return {"number": num, "kind": "proficiency", "name": name_at(TABLES["weapon_types"], num - PROF_BASE), "learned": learned}
    kind = "spell" if table is TABLES["spells"] else "skill"
    return {"number": num, "kind": kind, "name": name_at(table, num), "learned": learned}


class Reader:
    def __init__(self, data: bytes, where: str):
        self.d = data
        self.pos = 0
        self.where = where

    def eof(self) -> bool:
        return self.pos >= len(self.d)

    def raw(self, n: int) -> bytes:
        if self.pos + n > len(self.d):
            raise FormatError(f"{self.where}: truncated at offset {self.pos} (wanted {n} bytes)")
        b = self.d[self.pos:self.pos + n]
        self.pos += n
        return b

    def num(self, kind: str) -> int | float:
        fmt = FMT[kind]
        return struct.unpack(fmt, self.raw(struct.calcsize(fmt)))[0]

    def u8(self) -> int: return self.num("u8")
    def u16(self) -> int: return self.num("u16")
    def s32(self) -> int: return self.num("s32")
    def u32(self) -> int: return self.num("u32")

    def field(self, key: str) -> Any:
        """A value whose size and signedness come from the C struct field ``key``."""
        lay = LAYOUT[key]
        if lay["kind"] == "other":
            if lay["size"] == 32:   # u32[8] extended bitvector
                return list(struct.unpack("<8I", self.raw(32)))
            raise FormatError(f"{self.where}: no decoder for {key}")
        return self.num(lay["kind"])

    def sd(self) -> str:
        """ReadSD / _ReadSS: u16 length (including NUL) then bytes."""
        n = self.u16()
        b = self.raw(n)
        b = b.split(b"\0", 1)[0]
        try:
            return b.decode("utf-8")
        except UnicodeDecodeError:
            return b.decode("latin-1")

    def time32(self) -> int:
        return self.u32()

    def counted(self, elem_size: int) -> int:
        """ReadAS / ReadAD prefix: u16 byte count; returns element count."""
        n = self.u16()
        if n % elem_size:
            raise FormatError(f"{self.where}: array byte count {n} not a multiple of {elem_size} at {self.pos}")
        return n // elem_size

    def array(self, kind: str) -> list[Any]:
        size = struct.calcsize(FMT[kind])
        return [self.num(kind) for _ in range(self.counted(size))]

    def command_list(self) -> list[str]:
        """ReadCommandsList: s32 count then that many _ReadSS strings."""
        n = self.s32()
        return [self.sd() for _ in range(n)]


@dataclass
class Options:
    include_secrets: bool = False
    strict: bool = False
    warnings: list[str] = field(default_factory=list)

    def warn(self, msg: str) -> None:
        if self.strict:
            raise FormatError(msg)
        self.warnings.append(msg)
        print(f"warning: {msg}", file=sys.stderr)


