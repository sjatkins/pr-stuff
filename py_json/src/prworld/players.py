def read_sub(r: Reader, end: int, fields: dict[int, tuple[str, Callable[[], Any]]], what: str) -> dict[str, Any]:
    out: dict[str, Any] = {}
    while True:
        tag = r.u16()
        if tag == end:
            return out
        if tag not in fields:
            raise FormatError(f"{r.where}: unknown tag {tag} in {what} at {r.pos - 2}")
        name, fn = fields[tag]
        out[name] = fn()


def read_affect(r: Reader) -> dict[str, Any]:
    spells = TABLES["spells"]
    rec = read_sub(r, AFFECT_END, {
        1: ("type", lambda: r.field("af.type")),
        2: ("duration", lambda: r.field("af.duration")),
        3: ("modifier", lambda: r.field("af.modifier")),
        4: ("location", lambda: name_at(TABLES["apply_types"], r.field("af.location"))),
        5: ("bitvector", lambda: ext_bits(r.field("af.bitvector") if LAYOUT["af.bitvector"]["kind"] == "other"
                                          else list(struct.unpack("<8I", r.raw(32))), TABLES["affected_bits"])),
    }, "affect")
    if "type" in rec:
        rec["type_name"] = attack_name(rec["type"])
    return rec


