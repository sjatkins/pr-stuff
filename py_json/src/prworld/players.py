def read_obj_list(r: Reader, opt: Options) -> list[dict[str, Any]]:
    items: list[dict[str, Any]] = []
    while True:
        tag = r.u16()
        if tag == END_OF_LIST:
            return items
        if tag == OBJECT:
            items.append(read_object(r, opt))
        elif tag == SUB_OBJECT:
            if not items:
                raise FormatError(f"{r.where}: contents before any object at {r.pos}")
            items[-1]["contents"] = read_obj_list(r, opt)
        else:
            raise FormatError(f"{r.where}: unknown tag {tag} in object list at {r.pos - 2}")


def _apply_loop(r: Reader, fields: dict[int, tuple[str, Callable[[], Any]]]) -> list[dict[str, Any]]:
    """The ``while(1) { id; if 254 break; switch ... case 253: j++ }`` shape."""
    out: list[dict[str, Any]] = []
    cur: dict[str, Any] = {}
    while True:
        tag = r.u16()
        if tag == 254:
            if cur:
                out.append(cur)
            return out
        if tag == 253:
            out.append(cur)
            cur = {}
            continue
        if tag not in fields:
            raise FormatError(f"{r.where}: unknown apply tag {tag} at {r.pos - 2}")
        name, fn = fields[tag]
        cur[name] = fn()


def read_object(r: Reader, opt: Options) -> dict[str, Any]:
    o: dict[str, Any] = {"vnum": None, "name": None, "short_description": None,
                         "description": None, "contents": []}
    apply_types = TABLES["apply_types"]

    def fld(name: str, key: str):
        return lambda: o.__setitem__(name, r.field(key))

    def sd(name: str):
        # An empty saved string means "use the prototype's text" (ReadObject
        # copies it from the object database); null says that more honestly.
        return lambda: o.__setitem__(name, r.sd() or None)

    def value_array():
        o["value"] = r.array("s32")

    def old_apply():
        n = r.counted(LAYOUT["sizeof.old_obj_affected_type"]["size"])
        for _ in range(n):
            loc = r.u8(); r.raw(3); mod = r.s32()
            o.setdefault("apply", []).append({"location": name_at(apply_types, loc), "modifier": mod})

    def apply27():
        n = r.u8()
        for _ in range(n):
            loc = r.u8()
            mod = r.field("o.apply[0].modifier")
            o.setdefault("apply", []).append({"location": name_at(apply_types, loc), "modifier": mod})

    def apply62():
        rows = _apply_loop(r, {
            1: ("location", lambda: name_at(apply_types, r.field("o.apply[0].location"))),
            2: ("modifier", lambda: r.field("o.apply[0].modifier")),
            3: ("qualifier", lambda: r.field("o.apply[0].qualifier")),
        })
        o.setdefault("apply", []).extend(rows)

    def apply74():
        o["pulse_apply"] = _apply_loop(r, {
            1: ("location", lambda: name_at(apply_types, r.field("o.pulse_apply[0].location"))),
            2: ("modifier", lambda: r.field("o.pulse_apply[0].modifier")),
        })

    def apply83():
        o["socket_apply"] = _apply_loop(r, {
            1: ("vnum", lambda: r.field("o.socket_apply[0].vnum")),
            2: ("location", lambda: name_at(apply_types, r.field("o.socket_apply[0].location"))),
            3: ("modifier", lambda: r.field("o.socket_apply[0].modifier")),
            4: ("name", r.sd),
            5: ("identifier", lambda: r.field("o.socket_apply[0].identifier")),
            6: ("removable", lambda: r.field("o.socket_apply[0].removable")),
            7: ("unique", lambda: r.field("o.socket_apply[0].unique")),
        })

    def eq_pos():
        pos = r.field("o.eq_pos")
        o["eq_pos"] = None if pos < 0 else name_at(TABLES["wear_positions"], pos)

    def extra46():
        exs: list[dict[str, Any]] = []
        cur: dict[str, Any] | None = None
        while True:
            tag = r.u16()
            if tag == 254:
                break
            key = "keywords" if tag == 1 else "description"
            if cur is None or key in cur:
                cur = {}
                exs.append(cur)
            cur[key] = r.sd()
        o["extra_descriptions"] = exs

    handlers: dict[int, Callable[[], Any]] = {
        2: value_array,
        3: lambda: o.__setitem__("wear_flags", bits(r.field("o.wear_flags"), TABLES["wear_bits"])),
        4: lambda: o.__setitem__("extra_flags", bits(r.field("o.extra_flags"), TABLES["extra_bits"])),
        5: fld("intrinsic_weight", "o.intrinsic_weight"),
        6: fld("cost", "o.cost"),
        7: fld("cost_per_day", "o.cost_per_day"),
        8: fld("timer", "o.timer"),
        9: lambda: o.__setitem__("affects", ext_bits(list(struct.unpack("<8I", r.raw(32))), TABLES["affected_bits"])),
        10: fld("xtra_bits", "o.xtra_bits"),
        12: sd("name"), 13: sd("description"), 14: sd("short_description"), 15: sd("action_description"),
        16: eq_pos,
        17: fld("in_room", "o.in_room"),
        18: lambda: o.__setitem__("type", name_at(TABLES["item_types"], r.field("o.type_flag"))),
        19: fld("vnum", "o.vnum"),
        20: old_apply,
        21: fld("min_level", "o.min_level"),
        22: fld("time_stamp", "o.time_stamp"),
        23: lambda: r.s32(),
        24: fld("intrinsic_volume", "o.intrinsic_volume"),
        25: lambda: o.__setitem__("material", name_at(TABLES["material_types"], r.field("o.material"))),
        26: fld("length", "o.length"), 30: fld("width", "o.width"), 31: fld("height", "o.height"),
        27: apply27,
        28: fld("real_cost", "o.real_cost"),
        29: fld("timer2", "o.timer2"),
        32: fld("contents_volume", "o.contents_volume"),
        33: fld("contents_weight", "o.contents_weight"),
        34: sd("msg_to_room"), 35: sd("msg_to_char"), 36: sd("msg_to_dest"),
        37: fld("touch_to_room", "o.touch_to_room"),
        46: extra46,
        59: sd("owner"), 60: sd("held_for"),
        61: lambda: o.__setitem__("rarity", name_at(TABLES["rarity_types"], r.field("o.rarity"))),
        62: apply62,
        63: fld("mutation_count", "o.mutation_count"),
        64: fld("fixed", "o.fixed"),
        65: fld("use_cooldown", "o.use_cooldown"),
        66: fld("last_use_time", "o.last_use_time"),
        67: sd("loaded_by_imm"), 68: sd("edited_by_imm"), 69: sd("mutated_by_imm"), 70: sd("stringed_by_imm"),
        71: fld("created_date", "o.created_date"),
        72: fld("ws_cooldown", "o.ws_cooldown"),
        73: fld("last_use_time", "o.last_use_time"),
        74: apply74,
        75: fld("pulse_duration", "o.pulse_duration"),
        76: sd("pulse_finish_msg"),
        77: fld("item_set", "o.item_set"),
        78: sd("item_ability_desc"),
        79: fld("mm_crack_code", "o.mm_crack_code"),
        80: fld("mm_crack_attempts", "o.mm_crack_attempts"),
        81: fld("tier", "o.obj_tier"),
        82: fld("sockets", "o.sockets"),
        83: apply83,
    }
    while True:
        tag = r.u16()
        if tag == END_OF_OBJECT:
            return o
        h = handlers.get(tag)
        if h is None:
            raise FormatError(f"{r.where}: unknown object field {tag} at offset {r.pos - 2}")
        h()


